#!/usr/bin/env python3
"""Generate ro_grid_inst.vh: the 64 pinned ring instances included by ro_grid.v.

Picks, for each (column, row) target, the nearest SLICE site in a CLB tile
from prjxray-db's tilegrid, skipping the right-edge column (ro1 at X151 was
unreliable) and the slices used by the TDC / droop monitor carry chains.
Usage: gen_ro_grid.py <prjxray-db>/kintex7/xc7k325t/tilegrid.json > ro_grid_inst.vh
"""
import json, re, sys

g = json.load(open(sys.argv[1]))
sites = {}
for t in g.values():
    if t["type"].startswith("CLB"):
        for s in t["sites"]:
            m = re.match(r"SLICE_X(\d+)Y(\d+)$", s)
            if m:
                sites[(int(m.group(1)), int(m.group(2)))] = (s, t.get("clock_region"))
busy = set()
for y in range(98, 164): busy.add((82, y))    # TDC + its RO
for y in range(200, 264): busy.add((86, y))   # droop monitor chain
for x, y in [(0, 20), (151, 20), (145, 20), (80, 170), (0, 320), (145, 320)]:
    busy.add((x, y))                          # the 5 named ROs

XS = [4, 24, 44, 64, 84, 104, 124, 142]
YS = [20, 64, 108, 152, 196, 240, 284, 328]
out = ["// generated by tools/gen_ro_grid.py -- do not edit",
       "// index = row*8 + col; row 0 = bottom (Y small), col 0 = left (X small)"]
for r, ty in enumerate(YS):
    for c, tx in enumerate(XS):
        best = min((k for k in sites if k not in busy and k[0] < 150),
                   key=lambda k: (k[0] - tx) ** 2 + (k[1] - ty) ** 2)
        busy.add(best)
        i = r * 8 + c
        out.append('grid_ring #(.LOC("%s")) rg%d (.en(en[%d]), .out(ring[%d]));  // region %s'
                   % (sites[best][0], i, i, i, sites[best][1]))
print("\n".join(out))
